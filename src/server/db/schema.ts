/**
 * Database schema (Drizzle, PostgreSQL).
 *
 * The first five tables are Better Auth's core schema (field names must match its model; column
 * names are snake_case). The progress tables store the existing event-sourced progress model:
 * an append-only event log per user plus a derived snapshot that can always be rebuilt from it.
 *
 * Commercial entitlements (purchases, subscriptions) are intentionally NOT modelled yet; see
 * src/lib/access and docs/ARCHITECTURE.md for where they will plug in.
 */
import { sql } from "drizzle-orm";
import {
  bigint,
  bigserial,
  boolean,
  index,
  integer,
  jsonb,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
} from "drizzle-orm/pg-core";

// ---------------------------------------------------------------------------------------------
// Better Auth
// ---------------------------------------------------------------------------------------------

export const user = pgTable("user", {
  id: text("id").primaryKey(),
  name: text("name").notNull(),
  email: text("email").notNull().unique(),
  emailVerified: boolean("email_verified").notNull().default(false),
  image: text("image"),
  /** Permission role ("user" | "admin"). Not a commercial entitlement. Never settable by clients. */
  role: text("role").notNull().default("user"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
});

export const session = pgTable(
  "session",
  {
    id: text("id").primaryKey(),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
    token: text("token").notNull().unique(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
    ipAddress: text("ip_address"),
    userAgent: text("user_agent"),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
  },
  (t) => [index("session_user_id_idx").on(t.userId)],
);

export const account = pgTable(
  "account",
  {
    id: text("id").primaryKey(),
    accountId: text("account_id").notNull(),
    providerId: text("provider_id").notNull(),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    accessToken: text("access_token"),
    refreshToken: text("refresh_token"),
    idToken: text("id_token"),
    accessTokenExpiresAt: timestamp("access_token_expires_at", { withTimezone: true }),
    refreshTokenExpiresAt: timestamp("refresh_token_expires_at", { withTimezone: true }),
    scope: text("scope"),
    /** Password hash (scrypt) for email/password accounts. */
    password: text("password"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index("account_user_id_idx").on(t.userId)],
);

export const verification = pgTable(
  "verification",
  {
    id: text("id").primaryKey(),
    identifier: text("identifier").notNull(),
    value: text("value").notNull(),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index("verification_identifier_idx").on(t.identifier)],
);

/** Better Auth rate-limit counters (database storage survives restarts). */
export const rateLimit = pgTable("rate_limit", {
  id: text("id").primaryKey(),
  key: text("key").notNull().unique(),
  count: integer("count").notNull(),
  lastRequest: bigint("last_request", { mode: "number" }).notNull(),
});

// ---------------------------------------------------------------------------------------------
// Progress (event-sourced)
// ---------------------------------------------------------------------------------------------

/**
 * Append-only progress events. `eventId` is generated by the client; the unique (user, event)
 * index makes uploads idempotent: retries and duplicate submissions are ignored.
 */
export const progressEvent = pgTable(
  "progress_event",
  {
    seq: bigserial("seq", { mode: "number" }).primaryKey(),
    userId: text("user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    eventId: text("event_id").notNull(),
    type: text("type").notNull(),
    courseId: text("course_id"),
    lessonId: text("lesson_id"),
    /** The full validated event (without its id), as produced by the client reducer. */
    payload: jsonb("payload").notNull(),
    /** Client time the event happened (clamped server-side). Replay order key. */
    occurredAt: timestamp("occurred_at", { withTimezone: true }).notNull(),
    receivedAt: timestamp("received_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    uniqueIndex("progress_event_user_event_idx").on(t.userId, t.eventId),
    index("progress_event_user_order_idx").on(t.userId, t.occurredAt, t.eventId),
  ],
);

/** Derived cache: the result of replaying a user's events. Safe to delete and rebuild. */
export const progressSnapshot = pgTable("progress_snapshot", {
  userId: text("user_id")
    .primaryKey()
    .references(() => user.id, { onDelete: "cascade" }),
  state: jsonb("state").notNull(),
  eventCount: integer("event_count").notNull().default(0),
  updatedAt: timestamp("updated_at", { withTimezone: true })
    .notNull()
    .default(sql`now()`),
});

export const schema = { user, session, account, verification, rateLimit, progressEvent, progressSnapshot };

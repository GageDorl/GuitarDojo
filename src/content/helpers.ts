/**
 * Small authoring helpers that keep lesson files readable. They only build plain data.
 */
import type {
  CalloutBlock,
  ExerciseBlock,
  FretboardBlock,
  LessonBlock,
  LessonStep,
  TextBlock,
} from "@/lib/courses";
import type { Choice, DrillGenerator, Exercise, MultipleChoiceExercise } from "@/lib/exercises";
import {
  type FretboardSpec,
  type PentatonicPosition,
  lowStringFret,
  pentatonicPositionRange,
  rangeForVoicing,
} from "@/lib/fretboard";
import {
  type ChordSpec,
  type FretPosition,
  type FretRange,
  type ScaleTypeId,
  type VoicingSearchOptions,
  STANDARD_TUNING,
  buildChord,
  buildScale,
  findPitchClass,
  findVoicings,
  parseNote,
  parseVoicing,
  pitchClass,
  shiftVoicing,
  voicingPositions,
  voicingShape,
} from "@/lib/theory";

export const text = (body: string): TextBlock => ({ type: "text", body: dedent(body) });

export const callout = (tone: CalloutBlock["tone"], body: string, title?: string): CalloutBlock => ({
  type: "callout",
  tone,
  title,
  body: dedent(body),
});

export const board = (spec: FretboardSpec, caption?: string): FretboardBlock => ({ type: "fretboard", board: spec, caption });

export const exercise = (ex: Exercise): ExerciseBlock => ({ type: "exercise", exercise: ex });

export const step = (id: string, title: string, blocks: LessonBlock[]): LessonStep => ({ id, title, blocks });

/** Multiple choice with choices written as [id, label, feedback?]. */
export function choice(
  id: string,
  prompt: string,
  choices: [id: string, label: string, feedback?: string][],
  answer: string,
  extra: Partial<Pick<MultipleChoiceExercise, "board" | "hint" | "explanation">> = {},
): ExerciseBlock {
  return exercise({
    id,
    kind: "multiple-choice",
    prompt,
    choices: choices.map(([cid, label, feedback]): Choice => ({ id: cid, label, feedback })),
    answer,
    ...extra,
  });
}

/** Positions of a voicing shape such as "x32010". */
export const shape = (s: string): FretPosition[] => voicingPositions(parseVoicing(s));

/** Presentation presets. */
export const NECK = { mobile: "neck", desktop: "neck" } as const;
export const CHORD = { mobile: "chord", desktop: "chord" } as const;
/** Construction exercises: big vertical diagram on phones, neck on desktop. */
export const BUILD = { mobile: "chord", desktop: "neck" } as const;

/** A randomized recall drill (see src/lib/exercises/drills.ts). */
export function drill(
  id: string,
  prompt: string,
  generator: DrillGenerator,
  options: { rounds?: number; passScore?: number; hint?: string } = {},
): ExerciseBlock {
  return exercise({
    id,
    kind: "drill",
    prompt,
    generator,
    rounds: options.rounds ?? 8,
    passScore: options.passScore ?? 0.75,
    hint: options.hint,
  });
}

/** Board spec showing a chord voicing, framed automatically with the engine's range helper. */
export function voicingBoard(
  chord: ChordSpec,
  voicing: string,
  options: Partial<FretboardSpec> = {},
): FretboardSpec {
  return {
    chord: { ...chord, voicing },
    range: rangeForVoicing(parseVoicing(voicing)),
    labels: "interval",
    layout: CHORD,
    ...options,
  };
}

/** Voicing shapes for a chord generated by the engine (not hand-typed), simplest first. */
export function generatedVoicings(chord: ChordSpec, options: VoicingSearchOptions = {}): string[] {
  return findVoicings(STANDARD_TUNING, buildChord(chord.root, chord.quality), options).map(voicingShape);
}

/** Move a shape up the neck (open strings become a barre). */
export const moved = (s: string, frets: number): string => voicingShape(shiftVoicing(parseVoicing(s), frets));

type PositionMarker = NonNullable<FretboardSpec["positions"]>[number];

/**
 * Demo frames that add one marker per frame. Earlier markers stay visible (or fade to ghosts with
 * `ghostPrevious`), so students watch a pattern being built.
 */
export function buildUp(
  steps: { readonly at: PositionMarker; readonly caption: string }[],
  options: { ghostPrevious?: boolean } = {},
): { caption: string; board: Partial<FretboardSpec> }[] {
  return steps.map((step, i) => ({
    caption: step.caption,
    board: {
      positions: steps
        .slice(0, i + 1)
        .map((s, j) => (j < i && options.ghostPrevious ? { ...s.at, state: "ghost" as const } : s.at)),
    },
  }));
}

/** Every position of a scale along one string (frets 0–11): a computed solution for scale rules. */
export function scaleAlongString(root: string, type: ScaleTypeId, string: number, range: FretRange = { start: 0, end: 11 }): FretPosition[] {
  return buildScale(root, type).degrees.flatMap((d) => findPitchClass(STANDARD_TUNING, pitchClass(d.note), range, [string]));
}

/** Every position of a scale inside a fret window: a computed solution for scale rules. */
export function scaleInWindow(root: string, type: ScaleTypeId, range: FretRange, strings?: number[]): FretPosition[] {
  return buildScale(root, type).degrees.flatMap((d) => findPitchClass(STANDARD_TUNING, pitchClass(d.note), range, strings));
}

/** Every position of a note inside a fret window. */
export function notePositions(note: string, range: FretRange, strings?: number[]): FretPosition[] {
  return findPitchClass(STANDARD_TUNING, pitchClass(parseNote(note)), range, strings);
}

/** Fret window of pentatonic position n for a minor key (or a major key via its relative minor). */
export function pentatonicWindow(minorRoot: string, position: PentatonicPosition): FretRange {
  return pentatonicPositionRange(lowStringFret(minorRoot), position);
}

/** Allow indented template literals in content files. */
function dedent(s: string): string {
  const lines = s.replace(/^\n/, "").replace(/\s+$/, "").split("\n");
  const indent = Math.min(...lines.filter((l) => l.trim()).map((l) => l.match(/^ */)![0].length));
  return lines.map((l) => l.slice(indent)).join("\n");
}

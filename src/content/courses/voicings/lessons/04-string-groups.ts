import type { Lesson } from "@/lib/courses";
import type { Inversion } from "@/lib/theory";
import { NECK, callout, drill, exercise, generatedVoicings, shape, step, text, voicingBoard } from "@/content/helpers";

const C = { root: "C", quality: "major" } as const;
const GROUP = [4, 3, 2];
const inv = (inversion: Inversion) =>
  generatedVoicings(C, { strings: GROUP, inversion, range: { start: 0, end: 12 }, minStrings: 3, limit: 1 })[0]!;

const aMinor432 = generatedVoicings({ root: "A", quality: "minor" }, { strings: [4, 3, 2], range: { start: 0, end: 12 }, minStrings: 3, limit: 1 })[0]!;
const dMajor321 = generatedVoicings({ root: "D", quality: "major" }, { strings: [3, 2, 1], inversion: "root-position", range: { start: 0, end: 12 }, minStrings: 3, limit: 1 })[0]!;

export const stringGroups: Lesson = {
  id: "string-groups",
  title: "Triads on Every String Group",
  summary: "Three strings at a time, three inversions each: compact triads all over the neck.",
  kind: "lesson",
  estimatedMinutes: 12,
  objectives: [
    "Play triads on the 1-2-3, 2-3-4 and 3-4-5 string groups",
    "Find all three inversions on one string group",
    "Build any major or minor triad on any group",
  ],
  prerequisites: ["inversions-and-bass"],
  completion: { type: "all-exercises-solved" },
  steps: [
    step("groups", "String groups", [
      text(`
        A **string group** is three neighbouring strings. Each group can hold a complete triad, and on each group the triad comes in **three inversions** as you move up the neck.

        Small triads are what session guitarists use to stay out of the way of the bass and keyboard. They also show you exactly where every chord tone is.
      `),
      {
        type: "compare",
        items: [
          { title: "Root position", board: voicingBoard(C, inv("root-position")) },
          { title: "1st inversion", board: voicingBoard(C, inv("first-inversion")) },
          { title: "2nd inversion", board: voicingBoard(C, inv("second-inversion")) },
        ],
        caption: "C major on strings 4, 3 and 2, generated by the chord engine. The lowest string of the three carries the bass note.",
      },
      callout("tip", "On each group the three shapes cycle up the neck, then repeat 12 frets higher. Learn one shape well and you can find the next by moving each note up to the next chord tone.", "Moving between inversions"),
    ]),
    step("practice", "Practice", [
      exercise({
        id: "a-minor-4-3-2",
        kind: "fretboard",
        task: "construct",
        prompt: "Build **A minor** (A, C, E) on strings **4, 3 and 2**.",
        hint: "Near the nut: E on the D string (fret 2), A on the G string (fret 2), C on the B string (fret 1).",
        board: { range: { start: 0, end: 12 }, labels: "none", strings: GROUP, layout: NECK },
        selection: "per-string",
        rule: { type: "chord", chord: { root: "A", quality: "minor" }, strings: GROUP },
        solution: shape(aMinor432),
      }),
      exercise({
        id: "d-major-3-2-1-root",
        kind: "fretboard",
        task: "construct",
        prompt: "Build **D major in root position** on strings **3, 2 and 1**.",
        hint: "Root position: D must be on the G string, the lowest of the three.",
        board: { range: { start: 0, end: 12 }, labels: "none", strings: [3, 2, 1], layout: NECK },
        selection: "per-string",
        rule: { type: "chord", chord: { root: "D", quality: "major" }, strings: [3, 2, 1], inversion: "root-position" },
        solution: shape(dMajor321),
      }),
      drill(
        "string-group-drill",
        "Build triads on any string group, in any inversion.",
        {
          type: "chord-construction",
          roots: ["C", "G", "D", "A", "E", "F"],
          qualities: ["major", "minor"],
          stringGroups: [[3, 2, 1], [4, 3, 2], [5, 4, 3]],
          inversions: ["root-position", "first-inversion", "second-inversion"],
          range: { start: 0, end: 12 },
        },
        { rounds: 6, hint: "Find the bass note first on the lowest string of the group, then the other two tones above it." },
      ),
    ]),
  ],
};
